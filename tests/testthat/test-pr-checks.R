           "CONTRIBUTING.md", "DESCRIPTION", "_pkgdown.yml")
  no <- c("tests/testthat/test-x.R", "tests/testthat/fixtures/a.md",
          "inst/extdata/paper.md", "NAMESPACE", "docs/index.md", "src/x.md",
          "cran-comments.txt")
  expect_true(all(pc$dash_covered(yes)), info = paste(yes[!pc$dash_covered(yes)], collapse = ", "))
  expect_false(any(pc$dash_covered(no)), info = paste(no[pc$dash_covered(no)], collapse = ", "))
})

test_that("an added em dash, en dash or spaced double hyphen fails", {
  pc <- pr_checks()
  for (line in c(paste0("# The cache ", em, " keyed by spec."),
                 paste0("#' Pages 3", en, "5 are read."),
                 "# The cache -- keyed by spec.")) {
    v <- pc$dashes_verdict(pc$added_lines(fake_diff("R/doc-x.R", c("x <- 1", line))))
    expect_identical(v$status, 1L, label = line)
    expect_true(any(grepl("R/doc-x.R:11: ", v$out, fixed = TRUE)), label = line)
    expect_true(any(grepl(trimws(line), v$out, fixed = TRUE)), label = line)
    expect_true(any(grepl("Rewrite each sentence", v$out, fixed = TRUE)), label = line)
  }
  v <- pc$dashes_verdict(pc$added_lines(fake_diff("README.md", paste0("a ", em, " b ", en, " c -- d"))))
  expect_identical(v$status, 1L)
  expect_true(any(grepl("an em dash, an en dash, a spaced double hyphen", v$out, fixed = TRUE)))
})

test_that("dashes in tests/, in removed lines and in plain lines pass", {
  pc <- pr_checks()
  dashed <- c(paste0("x <- \"a ", em, " b\""), paste0("# 1", en, "2"), "# a -- b")
  expect_identical(pc$dashes_verdict(pc$added_lines(
    fake_diff("tests/testthat/test-x.R", dashed)))$status, 0L)
  expect_identical(pc$dashes_verdict(pc$added_lines(
    fake_diff("R/doc-x.R", "# The cache is keyed by spec.", removed = dashed)))$status, 0L)
  # Hyphens that are not a spaced double hyphen.
  ok <- c("x <- a - b", "# well-formed", "x--", "--flag", "# see --no-test-load",
          "x <- y ---z", "")
  v <- pc$dashes_verdict(pc$added_lines(fake_diff("dev/run.sh", ok)))
  expect_identical(v$status, 0L)
  expect_true(any(grepl("7 added line(s) checked", v$out, fixed = TRUE)))
  expect_identical(pc$dashes_verdict(pc$added_lines(character(0)))$status, 0L)
})

test_that("an allowlisted line keeps its double hyphen but not an em dash", {
  pc <- pr_checks()
  line <- "    \"section only -- no heading, no preamble.\","
  allowed <- "\"section only -- no heading,   no preamble.\","
  d <- pc$added_lines(fake_diff("R/doc-read-prompts.R", line))
  expect_identical(pc$dashes_verdict(d, allowed)$status, 0L)
  expect_identical(pc$dashes_verdict(d)$status, 1L)
  # Only the exact line text is allowed.
  other <- pc$added_lines(fake_diff("R/doc-read-prompts.R", "\"section -- other\","))
  expect_identical(pc$dashes_verdict(other, allowed)$status, 1L)
  with_em <- paste0("\"section only -- no heading", em, " no preamble.\",")
  d <- pc$added_lines(fake_diff("R/doc-read-prompts.R", with_em))
  expect_identical(pc$dashes_verdict(d, with_em)$status, 1L)
})

