# test-pr-checks.R: the verdicts of dev/ci/pr-checks.R, without git.
#
# The namespace and commits modes each decide from plain inputs (two
# NAMESPACE texts and the labels; a set of commit messages), so those
# functions are tested here directly. dev/ is not part of the built package,
# so these tests run from the source tree (run-tests.sh, the tests workflow)
# and skip under R CMD check.

pr_checks <- function() {
  path <- test_path("..", "..", "dev", "ci", "pr-checks.R")
  skip_if_not(file.exists(path), "dev/ci/pr-checks.R is not in an installed package")
  env <- new.env(parent = globalenv())
  sys.source(path, envir = env)
  env
}

ns_text <- function(...) c("# Generated by roxygen2: do not edit by hand", "",
                           "S3method(print,gr_answer)", ...)

test_that("sourcing pr-checks.R defines its functions and runs nothing", {
  pc <- pr_checks()
  for (f in c("namespace_exports", "namespace_verdict", "commit_problems",
              "commits_verdict", "shrink_only_added")) {
    expect_true(is.function(pc[[f]]), info = f)
  }
  expect_false(exists("check", envir = pc, inherits = FALSE))
})

test_that("export() lines are read one per name, whatever the quoting", {
  pc <- pr_checks()
  txt <- ns_text("export(gr_read)", "export(\"gr_ingest\")", "export(`%>>%`)",
                 "export(a, b)", "  export( hr_call )", "# export(commented_out)",
                 "exportPattern(\"^gr_\")", "importFrom(stats,sd)")
  expect_identical(pc$namespace_exports(txt),
                   sort(c("%>>%", "a", "b", "gr_ingest", "gr_read", "hr_call"), method = "radix"))
  expect_identical(pc$namespace_exports(character(0)), character(0))
})

test_that("a removed export fails without exports-reviewed and passes with it", {
  pc <- pr_checks()
  base <- ns_text("export(answer_document)", "export(parse_text)", "export(gr_read)")
  head <- ns_text("export(answer_document)", "export(gr_read)", "export(gr_example)")
  v <- pc$namespace_verdict(base, head, character(0))
  expect_identical(v$status, 1L)
  expect_true(any(grepl("Exports removed (1): parse_text", v$out, fixed = TRUE)))
  expect_true(any(grepl("Exports added (1): gr_example", v$out, fixed = TRUE)))
  expect_true(any(grepl("exports-reviewed", v$out, fixed = TRUE)))

  v <- pc$namespace_verdict(base, head, c("deps-reviewed", "exports-reviewed"))
  expect_identical(v$status, 0L)
  expect_true(any(grepl("Allowed", v$out, fixed = TRUE)))
  # Another label does not stand in for it.
  expect_identical(pc$namespace_verdict(base, head, "tests-reviewed")$status, 1L)
})

test_that("added, reordered or unchanged exports pass", {
  pc <- pr_checks()
  base <- ns_text("export(a)", "export(b)")
  expect_identical(pc$namespace_verdict(base, base)$status, 0L)
  expect_identical(pc$namespace_verdict(base, ns_text("export(b)", "export(a)"))$status, 0L)
  expect_identical(pc$namespace_verdict(base, ns_text("export(a)", "export(b)",
                                                      "export(c)"))$status, 0L)
  # No NAMESPACE at the base (a new package): nothing to remove.
  expect_identical(pc$namespace_verdict(character(0), base)$status, 0L)
  # A rename is a removal.
  expect_identical(pc$namespace_verdict(base, ns_text("export(a)", "export(b2)"))$status, 1L)
})

test_that("commit messages with attribution, chat links or generator lines fail", {
  pc <- pr_checks()
  bad <- c(
    trailer = "Fix the cache key\n\nBody.\n\nCo-Authored-By: Someone <someone@example.com>",
    lower = "Fix it\n\nco-authored-by: Someone <s@example.com>",
    claude = "Fix it\n\nSee https://claude.ai/code/session_0123 for the discussion.",
    bare_host = "Fix it\n\nDiscussed at claude.ai/chat/abc.",
    chatgpt = "Fix it\n\nhttps://chatgpt.com/share/abc",
    session = "Fix it\n\nAgent-Session: https://example.com/sessions/42",
    session_id = "Fix it\n\nX-Session-Id: https://foo.dev/s/1",
    co_developed = "Fix it\n\nCo-Developed-By: Someone <s@example.com>",
    subdomain = "Fix x\n\nSee https://www.claude.ai/share/abc",
    subdomain_bare = "Fix x\n\nSee www.chatgpt.com/share/abc",
    pathed_host = "Fix x\n\nAsked at huggingface.co/chat",
    port = "Fix x\n\nclaude.ai:443/chat/abc",
    generated = "Fix it\n\n\U0001F916 Generated with [Some Tool](https://example.com)",
    generated_plain = "Fix it\n\nGenerated with a tool")
  for (nm in names(bad)) {
    expect_gt(length(pc$commit_problems(bad[[nm]])), 0L, label = nm)
  }
  v <- pc$commits_verdict(bad)
  expect_identical(v$status, 1L)
  expect_true(any(grepl(sprintf("%d of %d", length(bad), length(bad)), v$out, fixed = TRUE)))
  expect_true(any(grepl("Co-Authored-By trailer", v$out, fixed = TRUE)))
})

test_that("commit messages that only mention tools or AI terms pass", {
  pc <- pr_checks()
  ok <- c(
    a = "Add an LLM judge for RAG answers\n\nThe judge asks a model whether each answer is supported.",
    b = "Record golden fixtures\n\nThe fixtures were generated with dev/record-golden.R.",
    c = "Document the Claude and OpenAI clients\n\nSee https://docs.anthropic.com/ and https://example.ai/x.",
    d = "Read co-authored papers correctly\n\nA paper co-authored by two groups keeps both.",
    e = "Mention notclaude.ai.example.com in a test fixture",
    f = "Mention Claude and ChatGPT in docs; the claude.ai option name",
    g = "Name chatgpt.com and claude.ai. Both are hosts, not links.",
    h = "Link https://claude.ai.example.com/x and https://notclaude.ai/x",
    i = "Keep the session: one request per session")
  for (nm in names(ok)) {
    expect_identical(pc$commit_problems(ok[[nm]]), character(0), label = nm)
  }
  v <- pc$commits_verdict(ok)
  expect_identical(v$status, 0L)
  expect_identical(pc$commits_verdict(character(0))$status, 0L)
})

test_that("only rows added to a shrink-only list count, not rows moved", {
  pc <- pr_checks()
  expect_identical(pc$shrink_only_added(c("\"b\"", "\"c\""), c("\"b\"")), "\"c\"")
  expect_identical(pc$shrink_only_added(c("\"b\""), c("\"a\"", "\"b\"")), character(0))
  expect_identical(pc$shrink_only_added(c("", "  "), character(0)), character(0))
})
